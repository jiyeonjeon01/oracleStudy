ALTER TABLE EMPLOYEE ADD CONSTRAINT EMPLOYEE_DEPARTMENT_DEPID_FK
    FOREIGN KEY(FKDEPID) REFERENCES DEPARTMENT(DEPID) ON DELETE CASCADE;


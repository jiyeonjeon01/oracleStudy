-- 2) 직원 테이블(직원정보, 시급)-------------------
DROP TABLE EMPLOYEE;
CREATE TABLE EMPLOYEE(
    EMPID NUMBER, -- PK, 직원ID
    NAME VARCHAR2(20) NOT NULL,-- 직원 이름

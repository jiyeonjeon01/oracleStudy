-- 4) 지급 내역 테이블 (직원정보, 지급 내역 등)
DROP TABLE HISTORY;
CREATE TABLE HISTORY (
    HISTORYID NUMBER, -- PK, 지급 기록 ID
    H_EMPID NUMBER NOT NULL,  -- FK, 직원 ID
    H_WHID NUMBER NOT NULL,  -- FK, 근무시간 ID
    PAY_DATE DATE NOT NULL,   -- 지급 날짜
    AMOUNT NUMBER NOT NULL,   -- 지급 금액
